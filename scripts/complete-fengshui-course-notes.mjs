function cueTimes(path) {
  const lines = readFileSync(path, 'utf8').replace(/\r/g, '').split('\n')
  const result = []
  for (let i = 0; i < lines.length; i += 1) {
    const match = lines[i].match(/^(\d{2}:\d{2}:\d{2})[.,]\d{3}\s+-->\s+(\d{2}:\d{2}:\d{2})/)
    if (!match) continue
    const words = []
    while (++i < lines.length && lines[i].trim()) words.push(lines[i].trim())
    // Very short subtitle cues are still valid source references; the note
    // deliberately cites a representative range, not a whole spoken sentence.
    if (words.join('').length > 0) result.push({ start: match[1], end: match[2] })
  }
  const at = fraction => result[Math.min(result.length - 1, Math.floor(result.length * fraction))]
  return [at(.15), at(.5), at(.82)].filter(Boolean)
}

